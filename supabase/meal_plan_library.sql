-- Run in the Supabase SQL Editor AFTER admin_and_meal_plans.sql, seed_recipes.sql,
-- tap_cook.sql and seed_more_recipes.sql. Safe to run again: it updates the
-- library plans in place. The last query lists any recipe a plan needs that
-- isn't in your database (it should come back with no rows).

-- 1. New columns
alter table meal_plans add column if not exists plan_key text;
alter table meal_plans add column if not exists is_library boolean default false;
alter table meal_plans add column if not exists calories int;
alter table meal_plans add column if not exists protein_min int;
alter table meal_plans add column if not exists protein_max int;
alter table meal_plans add column if not exists audience text;      -- her | him
alter table meal_plans add column if not exists editions text[];    -- which editions can browse it
alter table meal_plans add column if not exists image text;
alter table meal_plans add column if not exists sort_order int;
create unique index if not exists meal_plans_plan_key on meal_plans (plan_key);
alter table meal_plan_items add column if not exists servings numeric default 1;

-- 2. Members can browse library plans for their edition
drop policy if exists "Members browse library meal plans" on meal_plans;
create policy "Members browse library meal plans" on meal_plans for select using (
  is_library and (editions is null or public.my_edition() = any (editions))
);
drop policy if exists "Members see library meal plan items" on meal_plan_items;
create policy "Members see library meal plan items" on meal_plan_items for select using (
  exists (
    select 1 from meal_plans p
    where p.id = meal_plan_items.plan_id
      and p.is_library and (p.editions is null or public.my_edition() = any (p.editions))
  )
);

